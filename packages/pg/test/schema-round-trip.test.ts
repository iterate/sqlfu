// `draft`, `check` and `generate` re-read a Postgres schema as SQL text (via
// `materializeSchemaSql` / `extractSchemaFromClient`) and then diff that text
// against other schemas. If the text loses anything, every later diff sees a
// phantom change, or the text doesn't even replay. So: render, then diff the
// rendering against the original, in both directions. Both should be empty.
import {Pool} from 'pg';
import {expect, test} from 'vitest';

import {createNodePostgresClient, type SqlfuHost} from 'sqlfu';

import {pgDialect} from '../src/index.js';
import {startTempDatabase, TEST_ADMIN_URL} from './pg-fixture.js';

const dialect = pgDialect({adminUrl: TEST_ADMIN_URL});
const stubHost = {} as unknown as SqlfuHost;

test.for([
  {
    shape: 'plain tables, foreign keys, checks, indexes',
    schema: `
      create table authors (id uuid primary key default gen_random_uuid(), name text not null check (name <> ''));
      create table posts (
        id uuid primary key default gen_random_uuid(),
        author_id uuid not null references authors(id) on delete cascade,
        slug text not null unique,
        body jsonb,
        tags text[] not null default '{}'
      );
      create index posts_author_idx on posts (author_id);
    `,
  },
  {
    shape: 'views',
    schema: `
      create table posts (id uuid primary key, title text not null);
      create view post_titles as select id, title from posts;
    `,
  },
  {
    shape: 'serial and bigserial',
    schema: `create table posts (id serial primary key, view_count bigserial, title text);`,
  },
  {
    shape: 'identity columns',
    schema: `
      create table posts (id integer generated always as identity primary key, title text);
      create table comments (id bigint generated by default as identity primary key, body text);
    `,
  },
  {
    shape: 'enums',
    schema: `
      create type post_status as enum ('draft', 'published');
      create table posts (id uuid primary key, status post_status not null default 'draft');
    `,
  },
  {
    shape: 'domains',
    schema: `
      create domain email as text check (value like '%@%');
      create table users (id uuid primary key, email email not null);
    `,
  },
  {
    shape: 'domains over enums',
    schema: `
      create type color as enum ('red', 'orange', 'blue');
      create domain warm_color as color check (value in ('red', 'orange'));
      create table paints (id uuid primary key, color warm_color not null);
    `,
  },
  {
    shape: 'column collations',
    schema: `create table posts (id uuid primary key, slug text collate "C" not null default '' unique);`,
  },
  {
    shape: 'stored generated columns',
    schema: `create table users (id uuid primary key, name text not null, name_lower text generated always as (lower(name)) stored);`,
  },
  {
    shape: 'functions',
    schema: `create function slugify(input text) returns text language sql immutable as $$ select lower(replace(input, ' ', '-')) $$;`,
  },
  {
    shape: 'triggers',
    schema: `
      create table posts (id uuid primary key, title text not null, updated_at timestamptz);
      create function touch_updated_at() returns trigger language plpgsql as $$
      begin
        new.updated_at := now();
        return new;
      end
      $$;
      create trigger posts_touch before update on posts for each row execute function touch_updated_at();
    `,
  },
  {
    shape: 'materialized views',
    schema: `
      create table posts (id uuid primary key, title text not null);
      create materialized view post_count as select count(*) as total from posts;
      create unique index post_count_idx on post_count (total);
    `,
  },
  {
    shape: 'extensions',
    schema: `
      create extension citext;
      create table users (id uuid primary key, email citext not null unique);
    `,
  },
  {
    shape: 'schemas other than public',
    schema: `
      create schema billing;
      create table billing.invoices (id uuid primary key, total numeric(10, 2) not null);
      create view billing.big_invoices as select * from billing.invoices where total > 1000;
    `,
  },
])('materializeSchemaSql round-trips $shape', {timeout: 30_000}, async ({schema}) => {
  const rendered = await dialect.materializeSchemaSql(stubHost, {sourceSql: schema});

  expect(await diffBothWays(rendered, schema)).toEqual({renderedToOriginal: [], originalToRendered: []});
});

// migra creates every function and composite type after the tables, so a
// table that uses one can't be created from the rendering (or from a draft).
test.fails.for([
  {
    shape: 'a function called in a column default',
    schema: `
      create function new_short_id() returns text language sql as $$ select substr(md5(random()::text), 1, 8) $$;
      create table links (id text primary key default new_short_id(), url text not null);
    `,
  },
  {
    shape: 'a composite type as a column type',
    schema: `
      create type money_amount as (currency text, cents bigint);
      create table invoices (id uuid primary key, total money_amount not null);
    `,
  },
])('materializeSchemaSql round-trips $shape', {timeout: 30_000}, async ({schema}) => {
  const rendered = await dialect.materializeSchemaSql(stubHost, {sourceSql: schema});

  expect(await diffBothWays(rendered, schema)).toEqual({renderedToOriginal: [], originalToRendered: []});
});

test('extractSchemaFromClient round-trips a live database', {timeout: 30_000}, async () => {
  const schema = `
    create extension citext;
    create schema billing;
    create type post_status as enum ('draft', 'published');
    create domain email as citext check (value like '%@%');
    create table users (id serial primary key, email email not null unique);
    create table posts (
      id integer generated always as identity primary key,
      author_id integer not null references users(id),
      status post_status not null default 'draft',
      title text not null,
      slug text generated always as (lower(replace(title, ' ', '-'))) stored
    );
    create table billing.invoices (id bigserial primary key, user_id integer not null references users(id));
    create materialized view post_counts as select author_id, count(*) as total from posts group by author_id;
  `;
  await using database = await startTempDatabase();
  const pool = new Pool({connectionString: database.url, max: 1});
  try {
    const client = createNodePostgresClient(pool);
    await client.raw(schema);

    const extracted = await dialect.extractSchemaFromClient(client);

    expect(await diffBothWays(extracted, schema)).toEqual({renderedToOriginal: [], originalToRendered: []});
  } finally {
    await pool.end();
  }
});

test('excludedTables leaves out the table and everything attached to it', {timeout: 30_000}, async () => {
  const rendered = await dialect.materializeSchemaSql(stubHost, {
    sourceSql: `
      create table sqlfu_migrations (id serial primary key, name text not null unique check (name <> ''));
      create index sqlfu_migrations_name_idx on sqlfu_migrations (name);
      create table posts (id serial primary key);
    `,
    excludedTables: ['sqlfu_migrations'],
  });

  expect(rendered).not.toContain('sqlfu_migrations');
  expect(await diffBothWays(rendered, `create table posts (id serial primary key);`)).toEqual({
    renderedToOriginal: [],
    originalToRendered: [],
  });
});

async function diffBothWays(rendered: string, original: string) {
  return {
    renderedToOriginal: await dialect.diffSchema(stubHost, {
      baselineSql: rendered,
      desiredSql: original,
      allowDestructive: true,
    }),
    originalToRendered: await dialect.diffSchema(stubHost, {
      baselineSql: original,
      desiredSql: rendered,
      allowDestructive: true,
    }),
  };
}
